# PyTorch removed ReduceLROnPlateau's `verbose` argument (deprecated in 2.2, gone
# by 2.6) and the release still passes verbose=True, so it cannot start at all on
# a current torch. Patched here rather than in the release, which stays
# read-only. The argument only ever controlled whether a line was printed when
# the rate dropped -- it reaches no tensor, so this changes no number. Any
# *other* incompatibility would be a real difference and must not be papered
# over this way.
_ReduceLROnPlateau = _sched.ReduceLROnPlateau


class _CompatPlateau(_ReduceLROnPlateau):
    def __init__(self, *args, verbose=False, **kwargs):
        super().__init__(*args, **kwargs)


_sched.ReduceLROnPlateau = _CompatPlateau

